/** Shell completions and the man page, generated from the same `--help` text. */

import process from 'node:process'
import { FatalError } from './errors/fatal.ts'

export const COMPLETION_SHELLS = ['bash', 'zsh', 'fish', 'pwsh'] as const

const COMPLETION_HELP = `usage: engined completion <bash|zsh|fish|pwsh>

Print a shell completion script for that shell to stdout.
`

const MAN_HELP = `usage: engined man

Print the engined(1) man page to stdout.
`

const PATH_FLAGS = new Set(['--prune-config', '--out', '--caddyfile'])
const WHITESPACE = /\s/

export function helpCommands(help: string): string[] {
  const marker = '\ncommands:\n'
  const start = help.indexOf(marker)
  if (start === -1) {
    return []
  }
  let rest = help.slice(start + marker.length)
  const flagsAt = rest.indexOf('\nflags:')
  if (flagsAt !== -1) {
    rest = rest.slice(0, flagsAt)
  }
  const names: string[] = []
  for (const line of rest.split('\n')) {
    const [token] = line.trimStart().split(WHITESPACE)
    if (token?.startsWith('-')) {
      names.push(token)
    }
  }
  return names
}

function helpFlagTokens(help: string): string[] {
  return [...new Set(help.match(/-h|--[a-z][a-z0-9-]*/g) ?? [])]
}

function isShell(shell: string): shell is (typeof COMPLETION_SHELLS)[number] {
  return (COMPLETION_SHELLS as readonly string[]).includes(shell)
}

export function generateCompletion(shell: string, help: string): string {
  if (!isShell(shell)) {
    throw new Error(
      `unknown shell ${JSON.stringify(shell)}; supported: ${COMPLETION_SHELLS.join(', ')}`,
    )
  }
  const commands = helpCommands(help)
  const flags = helpFlagTokens(help)
  const cmds = commands.join(' ')
  const flagStr = flags.join(' ')
  const scripts = {
    bash: () => bashCompletion(cmds, flagStr),
    zsh: () => zshCompletion(cmds, flagStr),
    fish: () => fishCompletion(commands, flags),
    pwsh: () => pwshCompletion(cmds, flagStr),
  }
  return scripts[shell]()
}

export function generateMan(help: string): string {
  const lines = [
    '.TH ENGINED 1',
    '.SH NAME',
    'engined \\- local model door',
    '.SH DESCRIPTION',
    '.nf',
    '.na',
  ]
  for (const line of help.split('\n')) {
    let escaped = line.replaceAll('\\', '\\\\')
    if (escaped.startsWith('.') || escaped.startsWith("'")) {
      escaped = `\\&${escaped}`
    }
    lines.push(escaped === '' ? '.' : escaped)
  }
  lines.push('.ad', '.fi', '')
  return lines.join('\n')
}

export function completionExit(
  args: readonly string[],
  help: string,
  write: (s: string) => void,
): number {
  let shell: string | undefined
  for (const a of args) {
    if (a === '--help' || a === '-h') {
      write(COMPLETION_HELP.trimEnd())
      return 0
    }
    if (shell !== undefined) {
      return completionUsage(
        'completion requires exactly one shell argument (bash, zsh, fish, or pwsh)',
      )
    }
    shell = a
  }
  if (shell === undefined) {
    return completionUsage(
      'completion requires exactly one shell argument (bash, zsh, fish, or pwsh)',
    )
  }
  try {
    write(generateCompletion(shell, help).trimEnd())
    return 0
  } catch (err) {
    return completionUsage(err instanceof Error ? err.message : String(err))
  }
}

export function manExit(args: readonly string[], help: string, write: (s: string) => void): number {
  for (const a of args) {
    if (a === '--help' || a === '-h') {
      write(MAN_HELP.trimEnd())
      return 0
    }
    process.stderr.write('engined: man takes no arguments\n')
    process.stderr.write(MAN_HELP)
    return FatalError.USAGE_EXIT_CODE
  }
  write(generateMan(help).trimEnd())
  return 0
}

function completionUsage(message: string): number {
  process.stderr.write(`engined: ${message}\n${COMPLETION_HELP}`)
  return FatalError.USAGE_EXIT_CODE
}

function pathFlagTest(flags: Iterable<string>): string {
  return [...flags].map((f) => `"$prev" == "${f}"`).join(' || ')
}

function bashCompletion(cmds: string, flags: string): string {
  const pathTest = pathFlagTest(PATH_FLAGS)
  return `# engined bash completion -- generated by \`engined completion bash\`.
_engined() {
    local cur prev
    COMPREPLY=()
    cur="\${COMP_WORDS[COMP_CWORD]}"
    prev="\${COMP_WORDS[COMP_CWORD-1]}"
    if [[ ${pathTest} ]]; then
        COMPREPLY=( $(compgen -f -- "$cur") )
        return 0
    fi
    if [[ "$prev" == "completion" ]]; then
        COMPREPLY=( $(compgen -W "${COMPLETION_SHELLS.join(' ')}" -- "$cur") )
        return 0
    fi
    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "${flags}" -- "$cur") )
        return 0
    fi
    COMPREPLY=( $(compgen -W "${cmds} completion man" -- "$cur") )
}
complete -F _engined engined
`
}

function zshCompletion(cmds: string, flags: string): string {
  const pathTest = pathFlagTest(PATH_FLAGS)
  return `#compdef engined
# engined zsh completion -- generated by \`engined completion zsh\`.
_engined() {
    local cur prev
    cur="\${words[CURRENT]}"
    prev="\${words[CURRENT-1]}"
    if [[ ${pathTest} ]]; then
        _files
        return
    fi
    if [[ "$prev" == "completion" ]]; then
        compadd -- ${COMPLETION_SHELLS.join(' ')}
        return
    fi
    if [[ "$cur" == -* ]]; then
        compadd -- ${flags}
        return
    fi
    compadd -- ${cmds} completion man
}
(( $+functions[compdef] )) && compdef _engined engined
`
}

function fishCompletion(cmds: string[], flags: string[]): string {
  const lines = [
    '# engined fish completion -- generated by `engined completion fish`.',
    'complete -c engined -f',
    `complete -c engined -n '__fish_use_subcommand' -a '${[...cmds, 'completion', 'man'].join(' ')}'`,
    `complete -c engined -n '__fish_seen_subcommand_from completion' -a '${COMPLETION_SHELLS.join(' ')}'`,
  ]
  for (const flag of flags) {
    if (flag.startsWith('--')) {
      let line = `complete -c engined -l ${flag.slice(2)}`
      if (PATH_FLAGS.has(flag)) {
        line += ' -r -F'
      }
      lines.push(line)
    } else if (flag.startsWith('-') && flag.length === 2) {
      lines.push(`complete -c engined -s ${flag.slice(1)}`)
    }
  }
  return `${lines.join('\n')}\n`
}

function pwshCompletion(cmds: string, flags: string): string {
  const shells = COMPLETION_SHELLS.map((s) => `'${s}'`).join(', ')
  return `# engined pwsh completion -- generated by \`engined completion pwsh\`.
$enginedCommands = '${cmds} completion man'.Split(' ')
$enginedFlags = '${flags}'.Split(' ')
Register-ArgumentCompleter -Native -CommandName engined -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $elements = @($commandAst.CommandElements)
    $prev = ''
    if ($elements.Count -ge 2) {
        $prev = [string]$elements[$elements.Count - 1].Extent.Text
        if ($elements[-1].Extent.EndOffset -ge $cursorPosition -and $elements.Count -ge 3) {
            $prev = [string]$elements[$elements.Count - 2].Extent.Text
        }
    }
    function Emit-Completion {
        param([string]$Text)
        if ($Text.StartsWith([string]$wordToComplete, [System.StringComparison]::OrdinalIgnoreCase)) {
            [System.Management.Automation.CompletionResult]::new($Text, $Text, 'ParameterValue', $Text)
        }
    }
    if ($prev -eq 'completion') {
        foreach ($shell in @(${shells})) { Emit-Completion -Text $shell }
        return
    }
    if ($wordToComplete.StartsWith('-')) {
        foreach ($flag in $enginedFlags) { Emit-Completion -Text $flag }
        return
    }
    foreach ($command in $enginedCommands) { Emit-Completion -Text $command }
}
`
}
